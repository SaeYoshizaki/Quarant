#!/usr/bin/env python3
"""Encryption view of the claims: what vendors said about encryption vs what the traffic showed.

Usage: encryption_view.py <claims.tsv> <observations.json> <dataset> <out.md>

Two axes:
- method: claims that name how traffic is encrypted (algorithm, key length,
  protocol version, forward secrecy) — compared with the negotiated TLS
  versions and cipher suites.
- coverage: claims that traffic is encrypted (SSL, HTTPS, "all data is
  encrypted") — compared with plaintext traffic, split into requests that
  carry content (body, URL parameters or an Authorization header) and those
  that do not.
Plaintext credentials (T3) and plaintext updates (T5) count as coverage.
Also writes one table of the observed encryption of every product, with or
without claims.
"""
import collections
import csv
import json
import re
import sys

ENC = re.compile(r"(?i)encrypt|\bssl\b|\btls\b|https|\baes\b|cipher|secure socket|transport layer|forward secrecy|\brsa\b")
METHOD = re.compile(r"(?i)\baes\b|\brsa\b|\d+[- ]?bit|forward secrecy|curve25519|\bsha|tls ?v?1\.|ecdh|hkdf|mfi-sap|station-to-|verschl")
JA = {"contradiction candidate": "食い違いの候補", "wording-only contradiction": "文言の上で食い違い",
      "consistent (as observed)": "一致（見えた範囲で）", "not visible": "見えない", "not assessable": "判定できない"}
ORDER = ["contradiction candidate", "wording-only contradiction", "consistent (as observed)", "not visible", "not assessable"]


def ja(j):
    for k, v in JA.items():
        if j.startswith(k):
            return v + j[len(k):]
    return j


def short(q, n=110):
    q = q.replace("|", "/")
    return q if len(q) <= n else q[:n].rsplit(" ", 1)[0] + " …"


def pct(c, n):
    return "<1%" if 0 < c * 100 < n else f"{100 * c // n}%"


def tls_summary(o):
    n = sum(t["count"] for t in o["tls"])
    if not n:
        return n, "", "", ""
    vers = collections.Counter()
    aes = collections.Counter()
    for t in o["tls"]:
        vers[t["version"]] += t["count"]
        m = re.search(r"AES_(128|256)|CHACHA20|3DES|RC4", t["cipher"])
        aes[m.group(0).replace("AES_", "AES-") if m else "other"] += t["count"]
    pfs = sum(t["count"] for t in o["tls"] if t["forward_secrecy"])
    v = ", ".join(f"{k.replace('TLSv1', 'TLS 1.')} {pct(c, n)}" for k, c in vers.most_common())
    a = ", ".join(f"{k} {pct(c, n)}" for k, c in aes.most_common())
    return n, v, a, pct(pfs, n)


def main():
    claims_tsv, obs_json, dataset, out = sys.argv[1:5]
    rows = [r for r in csv.DictReader(open(claims_tsv), delimiter="\t")
            if r["dataset"] == dataset and not r["quote"].startswith("(")]
    obs = {}
    for o in json.load(open(obs_json)):
        obs.setdefault(o["product"], []).append(o)
    enc = [r for r in rows if ENC.search(r["quote"]) or r["type"] in ("T1", "T2", "T3", "T4", "T5") and ENC.search(r["quote"] + r["note"])]
    for r in enc:
        r["axis"] = "method" if METHOD.search(r["quote"]) else "coverage"
        r["j"] = next(k for k in ORDER if r["judgment"].startswith(k))
    products = sorted({r["product"] for r in csv.DictReader(open(claims_tsv), delimiter="\t") if r["dataset"] == dataset})
    cat = {r["product"]: r["catalog_product"] for r in csv.DictReader(open(claims_tsv), delimiter="\t")}

    w = open(out, "w")
    w.write("<!-- generated by scripts/claims/encryption_view.py; do not edit by hand -->\n\n")
    c = collections.Counter((r["axis"], r["j"]) for r in enc)
    w.write(f"暗号化についての主張 {len(enc)} 件（{len({r['product'] for r in enc})} 製品）。\n\n")
    w.write("| 判定 | 暗号の方法 | 暗号化しているか | 計 |\n|---|---|---|---|\n")
    for j in ORDER:
        w.write(f"| {JA[j]} | {c[('method', j)]} | {c[('coverage', j)]} | {c[('method', j)] + c[('coverage', j)]} |\n")
    w.write(f"| 計 | {sum(v for (a, _), v in c.items() if a == 'method')} | {sum(v for (a, _), v in c.items() if a == 'coverage')} | {len(enc)} |\n")

    for axis, title in (("method", "暗号の方法の主張"), ("coverage", "暗号化しているかの主張")):
        w.write(f"\n### {title}（判定できたもの）\n\n| 製品 | 主張 | 文書 | 判定 | 根拠 |\n|---|---|---|---|---|\n")
        for r in sorted((r for r in enc if r["axis"] == axis and r["j"] != "not assessable"),
                        key=lambda r: (ORDER.index(r["j"]), r["product"])):
            w.write(f"| {r['product']} | {short(r['quote'])} | {r['doc']} {r['snapshot']} | {ja(r['judgment'])} | {short(r['evidence'], 160)} |\n")
        na = [r for r in enc if r["axis"] == axis and r["j"] == "not assessable"]
        w.write(f"\n判定できなかったもの：{len(na)} 件（理由は claims.tsv の note）。\n")

    w.write("\n### 製品ごとの観測（主張の有無に関係なく）\n\n")
    w.write("期間は YourThings の 2018-03-20、04-10〜12。TLS は握手が見えた接続の数と割合。平文の HTTP の「中身あり」は本文、URL のパラメータ、Authorization ヘッダーのどれかがある要求。\n\n")
    w.write("| 製品 | 暗号化の主張 | TLS の接続 | TLS の版 | 暗号 | 前方秘匿性 | 外部への平文 HTTP（中身あり／うち認証ヘッダー／中身なし） | LAN 内の平文 HTTP（中身あり） | FTP のログイン |\n")
    w.write("|---|---|---|---|---|---|---|---|---|\n")
    has_claim = collections.Counter(r["product"] for r in enc)
    for p in products:
        os_ = [o for o in obs.get(cat.get(p, ""), [])]
        if not os_:
            w.write(f"| {p} | {has_claim[p]} | （観測なし） | | | | | | |\n")
            continue
        o = os_[0]
        n, v, a, pfs = tls_summary(o)
        ph = o["plaintext_http"]
        ftp = sum(f["count"] for f in o["ftp"] if f["password"])
        w.write(f"| {p} | {has_claim[p]} | {n} | {v} | {a} | {pfs} | {ph['external_content']}／{o['plaintext_http_auth']['external']}／{ph['external_no_content']} | {ph['lan_content']} | {ftp or ''} |\n")
    w.close()


if __name__ == "__main__":
    main()
