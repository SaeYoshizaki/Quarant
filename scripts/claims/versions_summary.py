#!/usr/bin/env python3
"""Per product: the versions seen in plaintext on each capture day, the YourThings scorecard's version,
and whether the release notes we read mention the versions seen.

Usage: versions_summary.py <versions dir> <devices.tsv> <scorecards.tsv> <coverage.tsv> <snapshots dir> <out.md>

<versions dir> holds versions.py output, one yt-<day>.json per day. Values
that carry no product version are dropped: DHCP client names (udhcp,
dhcpcd), and values whose only numbers are protocol versions (UPnP/1.0,
HTTP/1.1, DLNADOC/1.50). A release-notes check looks for each version
number seen (a dotted number, an Apple build such as 15L211, or a 10-digit
Hue build) in the text of the D6 documents of that product in coverage.tsv.
"""
import collections
import csv
import json
import re
import sys
from pathlib import Path

GENERIC = re.compile(r"(?i)\b(upnp|http|dlnadoc|mozilla|applewebkit|safari|khtml|cfnetwork|darwin|okhttp|dalvik)/[\d.]+\+?")
DHCP = re.compile(r"^(udhcp|dhcpcd|android-dhcp)")
TOKEN = re.compile(r"\b(\d{1,3}(?:\.\d{1,6}){1,3}(?:-\d+)?|\d{2}[A-Z]\d{2,4}|\d{10})\b")


def main():
    vdir, devices_tsv, scorecards_tsv, coverage_tsv, snaps_dir, out = sys.argv[1:7]
    catalog = {r["label"]: f"{r['vendor']} {r['product']}" for r in csv.DictReader(open(devices_tsv), delimiter="\t")
               if r["dataset"] == "yourthings"}
    sc = {r["label"]: r for r in csv.DictReader(open(scorecards_tsv), delimiter="\t")}
    # release notes (D6) that were read, per catalog product, and their saved text
    texts = {}
    for p in Path(snaps_dir).glob("*.txt"):
        first, _, body = p.read_text(errors="ignore").partition("\n")
        texts[first.removeprefix("SOURCE ").strip().replace("id_/", "/")] = body
    notes = collections.defaultdict(list)
    for r in csv.DictReader(open(coverage_tsv), delimiter="\t"):
        if r["dataset"] == "yourthings" and r["doc"] == "D6" and r["status"] == "found" and r["url"] in texts:
            notes[r["catalog_product"]].append((r["snapshot"], r["url"], texts[r["url"]]))

    seen = collections.defaultdict(lambda: collections.defaultdict(set))
    days = []
    for f in sorted(Path(vdir).glob("yt-*.json")):
        day = f.stem[3:]
        days.append(day)
        for r in json.load(open(f)):
            v = r["value"]
            if DHCP.match(v) or not re.search(r"\d", GENERIC.sub("", v)):
                continue
            seen[r["label"]][(r["source"], r["field"], v)].add(day)
    # a token is a product version only if no more than two products show it (drops 1.0, 2.0 and the like)
    token_products = collections.defaultdict(set)
    for lab, vals in seen.items():
        for (_, _, v) in vals:
            for t in TOKEN.findall(GENERIC.sub("", v)):
                token_products[t].add(lab)

    w = open(out, "w")
    w.write("<!-- generated by scripts/claims/versions_summary.py; do not edit by hand -->\n\n")
    w.write("平文の通信に出ていた版（HTTP の User-Agent・Server、SSDP、URL のパラメータ、本文の版の欄、mDNS の TXT。`versions.py`）。"
            "識別子は *** に置き換えた。TLS だけで通信する機器の版は見えない。日付は UTC。\n\n")
    w.write("| 製品 | 出どころ | 値 | 見えた日 | YourThings の評価の版（評価日） | リリースノートに載っているか |\n|---|---|---|---|---|---|\n")
    for lab in sorted(seen, key=lambda x: catalog.get(x, x)):
        s = sc.get(lab, {})
        grade = f"{s.get('firmware', '')}（{s.get('evaluated', '')}）" if s else ""
        rn = notes.get(catalog.get(lab, ""), [])
        for (src, field, v), ds in sorted(seen[lab].items(), key=lambda x: (min(x[1]), x[0])):
            toks = [t for t in TOKEN.findall(GENERIC.sub("", v)) if len(token_products[t]) <= 2]
            if rn and toks:
                hits = [f"{t}（{snap}）" for t in toks for snap, _, body in rn if re.search(r"(?<![\d.])" + re.escape(t) + r"(?![\d.])", body)]
                check = "載っている：" + "、".join(dict.fromkeys(hits)) if hits else \
                    "載っていない（" + "、".join(snap for snap, _, _ in rn) + " の版）"
            else:
                check = "（リリースノートなし）" if not rn else ""
            when = ", ".join(f"{d[4:6]}-{d[6:]}" for d in sorted(ds))
            w.write(f"| {catalog.get(lab, lab)} | {src} {field} | `{v[:90]}` | {when} | {grade} | {check} |\n")
            grade = ""
    w.close()


if __name__ == "__main__":
    main()
