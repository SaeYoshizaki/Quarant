#!/usr/bin/env python3
"""ROADMAP Step 1-2: accuracy of Quarant's device category inference on the
UNSW IoT traces, against docs/assessment/unsw-categories.json.

Each analysis run (one capture day) gives, per device, the inventory's
category_candidate and category_confidence. Outcomes per device-day:
  correct  - the category is one the ground truth accepts (for non-IoT and
             outside-taxonomy devices, only GenericIoT is correct)
  abstain  - GenericIoT / no candidate for an IoT device in the taxonomy
  wrong    - any other category
Reported: coverage (not abstaining), precision of assigned categories,
precision per confidence label (calibration), per-device majority, and a
confusion matrix.

usage: category_accuracy.py TRUTH_JSON RUNS_DIR OUT_MD
"""
import collections
import glob
import json
import os
import sys

GENERIC = {"", "GenericIoT", "Unknown", None}
CONF_ORDER = ["very_low", "low", "medium", "high", "strong"]


def outcome(truth, pred):
    generic = pred in GENERIC
    if truth.get("non_iot") or truth.get("outside_taxonomy"):
        return "correct" if generic else "wrong"
    if generic:
        return "abstain"
    return "correct" if pred in truth["accept"] else "wrong"


def main():
    truth_path, runs_dir, out_md = sys.argv[1:4]
    truth = {d["mac"].lower(): d for d in json.load(open(truth_path))["devices"]}
    rows = []  # (day, mac, pred, conf, outcome)
    for inv in sorted(glob.glob(os.path.join(runs_dir, "*", "device_inventory.json"))):
        day = os.path.basename(os.path.dirname(inv))
        for d in json.load(open(inv)).get("devices") or []:
            mac = (d.get("mac_address") or "").lower()
            if mac not in truth or not d.get("observed_protocols"):
                continue
            pred = d.get("category_candidate") or ""
            conf = d.get("category_confidence") or ""
            rows.append((day, mac, pred, conf, outcome(truth[mac], pred)))
    # one row per device-day (a device can appear under several IPs); the
    # first row in IP order is scored, and disagreeing rows are counted
    preds_by_day = collections.defaultdict(set)
    for r in rows:
        preds_by_day[(r[0], r[1])].add(r[2] or "GenericIoT")
    split_days = sum(1 for v in preds_by_day.values() if len(v) > 1)
    seen, uniq = set(), []
    for r in rows:
        if (r[0], r[1]) not in seen:
            seen.add((r[0], r[1]))
            uniq.append(r)
    rows = uniq

    def summary(subset):
        n = len(subset)
        c = collections.Counter(r[4] for r in subset)
        assigned = [r for r in subset if r[2] not in GENERIC]
        prec = sum(1 for r in assigned if r[4] == "correct")
        return n, c, len(assigned), prec

    L = ["# Category inference accuracy (UNSW IoT traces 2016)", "",
         "Generated by `scripts/assessment/category_accuracy.py` from `device_inventory.json` of each day. "
         "Ground truth: [unsw-categories.json](unsw-categories.json) (labels by Claude, not yet reviewed by a human).", ""]
    groups = [("IoT devices in the taxonomy", [r for r in rows if not truth[r[1]].get("non_iot") and not truth[r[1]].get("outside_taxonomy")]),
              ("IoT devices outside the taxonomy", [r for r in rows if truth[r[1]].get("outside_taxonomy")]),
              ("Non-IoT devices (phones, laptops, tablet, gateway)", [r for r in rows if truth[r[1]].get("non_iot")]),
              ("All", rows)]
    L += ["## Device-days", "", "| Devices | Device-days | Correct | Abstain (GenericIoT) | Wrong | Category assigned | Precision of assigned |", "|---|---|---|---|---|---|---|"]
    for name, sub in groups:
        n, c, a, p = summary(sub)
        L.append(f"| {name} | {n} | {c['correct']} | {c['abstain']} | {c['wrong']} | {a} | {p}/{a}" + (f" ({100 * p / a:.0f}%)" if a else "") + " |")

    L += ["", "## Precision by confidence label (all devices, category assigned)", "", "| Confidence | Assigned | Correct | Precision |", "|---|---|---|---|"]
    by_conf = collections.defaultdict(lambda: [0, 0])
    for r in rows:
        if r[2] in GENERIC:
            continue
        by_conf[r[3]][0] += 1
        by_conf[r[3]][1] += r[4] == "correct"
    for k in sorted(by_conf, key=lambda x: CONF_ORDER.index(x) if x in CONF_ORDER else 99):
        a, p = by_conf[k]
        L.append(f"| {k or '(none)'} | {a} | {p} | {100 * p / a:.0f}% |")

    L += ["", "## Per device (most frequent prediction over the days it was seen)", "",
          "| Device | Truth | Days | Predictions (days) | Majority outcome |", "|---|---|---|---|---|"]
    per = collections.defaultdict(list)
    for r in rows:
        per[r[1]].append(r)
    for mac in sorted(per, key=lambda m: truth[m]["name"]):
        t = truth[mac]
        preds = collections.Counter((r[2] or "GenericIoT") + (f"/{r[3]}" if r[3] else "") for r in per[mac])
        maj = collections.Counter(r[2] for r in per[mac]).most_common(1)[0][0]
        tl = "non-IoT" if t.get("non_iot") else "outside taxonomy" if t.get("outside_taxonomy") else "/".join(t["accept"])
        L.append(f"| {t['name']} | {tl} | {len(per[mac])} | " + ", ".join(f"{k} ({v})" for k, v in preds.most_common()) +
                 f" | {outcome(t, maj)} |")

    L += ["", "## Confusion (device-days; truth = first accepted category)", ""]
    conf_m = collections.defaultdict(collections.Counter)
    for r in rows:
        t = truth[r[1]]
        tl = "non-IoT" if t.get("non_iot") else "outside" if t.get("outside_taxonomy") else t["accept"][0]
        conf_m[tl][r[2] or "GenericIoT"] += 1
    preds = sorted({p for v in conf_m.values() for p in v})
    L += ["| Truth \\ Predicted | " + " | ".join(preds) + " |", "|---|" + "---|" * len(preds)]
    for tl in sorted(conf_m):
        L.append(f"| {tl} | " + " | ".join(str(conf_m[tl][p] or "") for p in preds) + " |")
    missing = sorted(t["name"] for m, t in truth.items() if m not in per)
    L += ["", "Devices never seen with traffic: " + (", ".join(missing) or "none")]
    L += ["", f"Device-days whose profiles (one per IP address) disagree on the category: {split_days} of {len(preds_by_day)}"]
    open(out_md, "w").write("\n".join(L) + "\n")
    print("\n".join(L))


if __name__ == "__main__":
    main()
